# frozen_string_literal: true

require_relative "../../../lib/extras/lines_commander"

module CLI
  module Docker
    extend LinesCommander

    # Shared by every bin/dx docker/* command (see the `Docker.ensure_docker_installed`
    # call at the top of #call) instead of each carrying its own identical
    # check-and-abort method.
    #
    def self.ensure_docker_installed
      return if command_available?("docker")

      say "Docker is not installed."
      say "Please visit https://docs.docker.com/get-docker/"
      abort
    end

    # Naming and file paths used to build and start containers from
    # Dockerfile.dev and docker-compose.dev.yml
    #
    IMAGE_NAME   = "passerelle:ruby-4.0"
    PROJECT_NAME = "passerelle"

    # Generated by `bin/dx build` to save the image & project names
    # used by other `bin/dx` commands.
    #
    ENV_FILE = ".docker/docker-compose.dev.env"

    # Optional, untracked, developer-specific overrides for docker-compose
    # variable substitution (e.g. PORT).
    #
    LOCAL_ENV_FILE = ".docker/docker-compose.local.env"

    # Options passed to every `docker compose` invocation — tells it which
    # compose file makes up the project and which env-files feed its
    # variable substitution.
    #
    # Env-files are only included when present: `docker compose --env-file`
    # hard-fails on a missing file.
    #
    def self.compose_command_options
      options  = ["--file", "docker-compose.dev.yml"]
      options += ["--env-file", LOCAL_ENV_FILE] if File.exist?(LOCAL_ENV_FILE)
      options += ["--env-file", ENV_FILE]       if File.exist?(ENV_FILE)
      options
    end
  end
end
